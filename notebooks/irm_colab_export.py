def gradcam(img_batch, class_idx=None):
    img_batch = tf.convert_to_tensor(img_batch)
    with tf.GradientTape() as tape:
        conv_maps, preds = grad_model(img_batch, training=False)
        if class_idx is None:
            class_idx = int(tf.argmax(preds[0]))
        score = preds[:, class_idx]
    grads = tape.gradient(score, conv_maps)
    poids = tf.reduce_mean(grads, axis=(1, 2))                    # importance de chaque filtre
    cam = tf.reduce_sum(conv_maps * poids[:, None, None, :], axis=-1)
    cam = tf.nn.relu(cam)[0]
    cam = cam / (tf.reduce_max(cam) + 1e-8)
    cam = tf.image.resize(cam[..., None], IMG_SIZE).numpy()[..., 0]
    return cam, preds[0].numpy()

