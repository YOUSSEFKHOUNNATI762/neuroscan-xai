def ece(probs, labels, n_bins=10):
    conf = probs.max(1); pred = probs.argmax(1); ok = (pred == labels)
    bins = np.linspace(0, 1, n_bins + 1); e = 0
    for lo, hi in zip(bins[:-1], bins[1:]):
        m = (conf > lo) & (conf <= hi)
        if m.any():
            e += m.mean() * abs(ok[m].mean() - conf[m].mean())
    return e

